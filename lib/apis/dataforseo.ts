/**
 * DataForSEO SERP provider (v7.397)
 * ───────────────────────────────────────────────────────────────────────────
 * A second SERP source behind the SAME contract SerpAPI already satisfies, so
 * `lib/apis/serp.ts` can dispatch to either provider without one downstream
 * caller changing. Every function here returns the EXACT types serp.ts returns
 * (imported as types below — `import type` is erased at compile time, so there
 * is no runtime cycle even though serp.ts imports this module).
 *
 * WHY (Wayne, 2026-08-03): SerpAPI is 76% of OrbitIQ's API bill ($219.27 of
 * $288.49) and carries a hard 30,000-searches/month ceiling that a single large
 * client can eat half of in one analysis (US Bank: 13,788 searches). DataForSEO
 * is pay-as-you-go with no ceiling at $0.002/SERP live vs SerpAPI's $0.0091667
 * effective — and it is the only provider in OrbitIQ that reports the REAL cost
 * of each request in its own response.
 *
 * ⭐ MEASURED COST (Const I.1). The response carries `cost` per task. That is a
 * real source row, not a rate × count estimate, so the usage ledger records the
 * ACTUAL dollars charged for every call. This is the first and only source in
 * OrbitIQ where spend is measured rather than derived; the published rate is
 * kept in the registry purely as a cross-check.
 *
 * Auth: HTTP Basic with the API login + API password from the DataForSEO
 * dashboard's API Access tab (the API password is generated by DataForSEO and
 * is NOT the account password). Docs: https://docs.dataforseo.com/v3/auth/
 *
 * Fault-tolerant by construction, exactly like serp.ts: every function catches
 * and returns an empty/false result so one bad call can never break a scan.
 */

